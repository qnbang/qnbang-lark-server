# -*- coding: utf-8 -*-
"""
'스타벅스 5500 식비 카드' 같은 글에서
날짜·카테고리·지출내용·비용·비고(결제수단)를 뽑아냅니다.

해석(원문) -> 딕셔너리
  성공: {"ok": True, "날짜": "2026/06/05", "카테고리": "식비",
         "지출 내용": "스타벅스", "비용": 5500, "비고": "카드", "추정분류": False}
  실패: {"ok": False, "이유": "금액이 안 보여요"}
"""

import re
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

서울 = ZoneInfo("Asia/Seoul")

# 큐앤뱅 고정 8개 분류
카테고리목록 = ["실비", "업무비", "식비", "프로그램 사용료", "월세&공과금", "재료비", "세금", "급여"]

# 분류 추정용 키워드 (정확히 카테고리명을 안 써도 추측)
분류키워드 = {
    "식비": ["식비", "밥", "점심", "저녁", "아침", "커피", "카페", "스타벅스", "회식", "간식", "음료", "디저트"],
    "업무비": ["업무비", "택시", "교통", "주차", "사무", "문구", "택배", "배송", "우편"],
    "재료비": ["재료비", "재료", "자재", "촬영", "소품", "부자재"],
    "프로그램 사용료": ["프로그램", "구독", "소프트웨어", "어도비", "노션", "챗gpt", "gpt", "saas", "라이선스"],
    "월세&공과금": ["월세", "공과금", "전기", "수도", "가스", "관리비", "인터넷", "임대"],
    "세금": ["세금", "부가세", "원천세", "세무"],
    "급여": ["급여", "월급", "인건비", "알바비", "임금"],
    "실비": ["실비"],
}

결제수단키워드 = ["법인카드", "개인카드", "신용카드", "체크카드", "카드", "현금", "계좌이체", "이체", "페이", "간편결제"]


def _금액파싱(text):
    """문자열에서 금액(원)과 그 위치를 찾습니다."""
    m = re.search(r'(\d+)\s*만\s*(\d+)?\s*천?', text)
    if m:
        만 = int(m.group(1))
        천 = int(m.group(2)) if m.group(2) else 0
        return 만 * 10000 + 천 * 1000, m.span()
    m = re.search(r'(\d+)\s*천', text)
    if m:
        return int(m.group(1)) * 1000, m.span()
    m = re.search(r'(\d[\d,]*)\s*원?', text)
    if m:
        return int(m.group(1).replace(",", "")), m.span()
    return None, None


def 해석(원문):
    남은 = " " + 원문.strip() + " "
    오늘 = datetime.now(서울).date()
    날짜 = 오늘
    추정분류 = False

    # ---- 날짜 ----
    for 말, d in [("그저께", 2), ("그제", 2), ("어제", 1), ("오늘", 0), ("금일", 0)]:
        if 말 in 남은:
            날짜 = 오늘 - timedelta(days=d)
            남은 = 남은.replace(말, " ", 1)
            break
    else:
        m = re.search(r'(\d{1,2})\s*월\s*(\d{1,2})\s*일?', 남은)
        if m:
            try:
                날짜 = datetime(오늘.year, int(m.group(1)), int(m.group(2))).date()
                남은 = 남은[:m.start()] + " " + 남은[m.end():]
            except ValueError:
                pass

    # ---- 카테고리 (정확한 이름 우선) ----
    카테고리 = None
    for 이름 in 카테고리목록:
        if 이름 in 남은:
            카테고리 = 이름
            남은 = 남은.replace(이름, " ", 1)
            break

    # ---- 비고(결제수단) ----
    비고 = ""
    for 말 in 결제수단키워드:
        if 말 in 남은:
            비고 = 말
            남은 = 남은.replace(말, " ", 1)
            break

    # ---- 금액 ----
    비용, span = _금액파싱(남은)
    if 비용 is None:
        return {"ok": False, "이유": "금액이 안 보여요"}
    남은 = 남은[:span[0]] + " " + 남은[span[1]:]

    # ---- 지출 내용 (남은 글자) ----
    내용 = re.sub(r'[\s·\-,원]+', ' ', 남은).strip()

    # ---- 카테고리 추정 (정확한 이름이 없었으면 키워드로) ----
    if 카테고리 is None:
        소문자 = 원문.lower()
        for 이름, 키워드들 in 분류키워드.items():
            if any(k in 소문자 for k in 키워드들):
                카테고리 = 이름
                break
        if 카테고리 is None:
            카테고리 = "업무비"  # 못 찾으면 기본값
        추정분류 = True

    if not 내용:
        내용 = 카테고리

    return {
        "ok": True,
        "날짜": "%04d/%02d/%02d" % (날짜.year, 날짜.month, 날짜.day),
        "카테고리": 카테고리,
        "지출 내용": 내용,
        "비용": 비용,
        "비고": 비고,
        "추정분류": 추정분류,
    }


if __name__ == "__main__":
    import json
    for e in ["스타벅스 5500 식비 카드", "쿠팡 사무용품 32000", "어제 점심 김밥천국 8000 현금",
              "6월 3일 어도비 구독료 2만9천 법인카드", "택시비 12000", "그냥 잡담", "5만원 회식 법인카드"]:
        print(e, "->", json.dumps(해석(e), ensure_ascii=False))
