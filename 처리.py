# ---------------- 일정 ----------------
# 라크 일정방은 '캘린더 전용'이다. 날짜가 있는 글은 모두 구글 캘린더에 등록한다.
# (할 일은 라크로 넣지 않는다 — 보드에서 직접/클로드로 관리.)
def _완료문구(결과):
    if 결과["종일"]:
        d = datetime.strptime(결과["시작"], "%Y-%m-%d")
        때 = "%d월 %d일(%s) 종일" % (d.month, d.day, 요일이름[d.weekday()])
    else:
        d = datetime.strptime(결과["시작"], "%Y-%m-%dT%H:%M:%S")
        오전오후 = "오전" if d.hour < 12 else "오후"
        시 = d.hour % 12 or 12
        때 = "%d월 %d일(%s) %s %d:%02d" % (d.month, d.day, 요일이름[d.weekday()], 오전오후, 시, d.minute)
    return "✅ 등록됨 — %s / %s (큐앤뱅 캘린더)" % (결과["제목"], 때)


def 일정메시지처리(토큰, chat_id, 본문, 트리거="", 글ID=None):
    if 트리거 and not 본문.startswith(트리거):
        return False
    if not 본문:
        return False

    # '이번 주 일정 알려줘' 같은 물어보는 글
    if 질의.질의인가(본문):
        시작d, 끝d, 라벨 = 질의.범위(본문)
        시작ISO = 시작d.isoformat() + "T00:00:00+09:00"
        끝ISO = (끝d + timedelta(days=1)).isoformat() + "T00:00:00+09:00"
        이벤트 = calendar_api.일정목록(시작ISO, 끝ISO)
        lark.메시지보내기(토큰, chat_id, 질의.응답만들기(라벨, 이벤트))
        return True

    # 캘린더 전용: 날짜가 있으면 구글 캘린더에 일정으로 등록(시간 없으면 종일).
    결과 = parse_schedule.해석(본문, 트리거, 시간필수=False)

    # 날짜가 없는 글은 잡담으로 보고 무시(트리거가 있으면 되묻기)
    if not 결과["ok"]:
        if 트리거:
            lark.메시지보내기(
                토큰, chat_id,
                "❓ '%s' — %s. 날짜를 넣어 다시 보내주세요. 예) '6월 6일 오후 3시 팀미팅'" % (본문, 결과["이유"]),
            )
            return True
        return False

    try:
        calendar_api.일정등록(
            결과["제목"], 결과["시작"], 결과["끝"],
            종일=결과["종일"], 설명="라크 일정방에서 자동 등록됨", 글ID=글ID,
        )
        lark.메시지보내기(토큰, chat_id, _완료문구(결과))
    except Exception as e:
        공용.로그().exception("일정 등록 실패 글ID=%s 본문=%s", 글ID, 본문[:40])
        lark.메시지보내기(토큰, chat_id, "⚠️ '%s' 처리 중 문제가 생겼어요: %s" % (본문, e))
    return True


# ---------------- 지출 ----------------
def _지출완료문구(r):
    날 = r["날짜"][5:]
    비고 = (" (%s)" % r["비고"]) if r["비고"] else ""
    문구 = "✅ 기록됨 — %s / %s %s원%s [%s]" % (
        r["카테고리"], r["지출 내용"], format(r["비용"], ","), 비고, 날)
    if r.get("추정분류"):
        문구 += "\n   (분류를 '%s'로 추정했어요. 다르면 분류명을 넣어 다시 보내주세요)" % r["카테고리"]
    return 문구


def 지출메시지처리(토큰, 지출설정, 본문):
    if not 본문:
        return False
    엔드포인트 = 지출설정["endpoint"]
    key = 지출설정["key"]
    chat_id = 지출설정["chat_id"]

    # '이번 달 지출 얼마' 같은 물어보는 글
    if 질의.질의인가(본문) or "얼마" in 본문 or "합계" in 본문:
        월별 = 시트.합계읽기(엔드포인트, key)
        줄 = ["💰 월별 지출"]
        for 월, 금액 in 월별.items():
            if 금액:
                줄.append("  %s  %s원" % (월, format(int(금액), ",")))
        합계 = sum(int(v) for v in 월별.values() if v)
        줄.append("  ─ 합계  %s원" % format(합계, ","))
        lark.메시지보내기(토큰, chat_id, "\n".join(줄))
        return True

    결과 = 지출해석.해석(본문)
    if not 결과["ok"]:  # 금액 없는 글은 잡담으로 무시
        return False

    try:
        시트.기록(엔드포인트, key, {
            "날짜": 결과["날짜"], "카테고리": 결과["카테고리"],
            "지출 내용": 결과["지출 내용"], "비용": 결과["비용"],
            "비고": 결과["비고"], "과업 관리": "",
        })
        lark.메시지보내기(토큰, chat_id, _지출완료문구(결과))
    except Exception as e:
        lark.메시지보내기(토큰, chat_id, "⚠️ '%s' 기록 중 문제가 생겼어요: %s" % (본문, e))
    return True


# ---------------- 매출(입금) ----------------
# 같은 지출방에 '입금'/'매출'이 들어간 글을 매출로 기록한다.
#  - 입금액이 기존 계약의 '계약금액'과 정확히 맞고 이름도 맞으면 → 그 계약 행에 입금 채우기(입금완료).
#  - 그 외(시트에 없는 새 계약)면 → 매출 탭에 새 줄 추가. 부가세는 '포함 총액'에서 자동 분리.
# 입력: "사단법인 점프 / 가치점프 월간 멘토링 디자인비 / 99만 입금" (슬래시로 클라이언트/계약명 구분 가능)
# 전제: 사장이 말하는 금액은 무조건 '부가세 포함 총액'.
def _금액(v):
    try:
        return int(float(v))
    except Exception:
        return 0


def _애매한가(후보정렬, 클라이언트):
    """확신이 낮아 자동기록 대신 되물어야 하는가.
    후보정렬=점수 내림차순, 각 원소 (점수, 금액정확일치, 계약명, 계약금액, 기존입금).
    - 거래처를 슬래시로 명시했으면 이미 그 거래처로 좁혔으니 애매판정 안 함.
    - 후보가 없으면(=새 계약 흐름) 애매판정 대상 아님.
    - 겹친 단어가 하나뿐이고 금액도 안 맞으면(공용단어 1개로 낚인 경우) 애매.
    - 똑같이 그럴듯한 후보가 둘 이상(동점)이어도 애매."""
    if not 후보정렬 or 클라이언트:
        return False
    최고점, 금액일치 = 후보정렬[0][0], 후보정렬[0][1]
    동점 = [c for c in 후보정렬 if c[0] == 최고점 and c[1] == 금액일치]
    return len(동점) >= 2 or (최고점 <= 1 and 금액일치 == 0)


def 매출메시지처리(토큰, 지출설정, 자금설정, 본문):
    if not 본문:
        return False
    결과 = 매출해석.해석(본문)
    if not 결과["ok"]:          # 금액 없는 글은 잡담으로 무시
        return False
    chat_id = 지출설정["chat_id"]
    입금액 = 결과["입금액"]
    힌트 = 결과["힌트"]
    클라이언트 = 결과.get("클라이언트", "")
    계약명입력 = 결과.get("계약명", "") or 힌트

    # 사용자가 '새 계약'이라고 명시하면 매칭을 건너뛰고 바로 새 매출 줄로 추가한다(사람 확인 게이트).
    강제신규 = any(k in 본문 for k in ("새계약", "새 계약", "신규계약", "신규 계약"))
    if 강제신규:
        for k in ("새계약", "새 계약", "신규계약", "신규 계약"):
            계약명입력 = 계약명입력.replace(k, "").strip()
            힌트 = 힌트.replace(k, "").strip()

    데이터 = 시트.탭읽기(지출설정["endpoint"], 지출설정["key"], "매출")
    if not 데이터 or len(데이터) < 2:
        lark.메시지보내기(토큰, chat_id, "⚠️ 매출 칸을 못 읽었어요. 잠시 후 다시 보내주세요.")
        return True
    헤더 = 데이터[0]
    i계약명 = 헤더.index("계약명") if "계약명" in 헤더 else -1
    i클 = 헤더.index("클라이언트") if "클라이언트" in 헤더 else -1
    i계약금액 = 헤더.index("계약금액") if "계약금액" in 헤더 else -1
    i입금액 = 헤더.index("입금액") if "입금액" in 헤더 else -1
    if i계약명 < 0 or i계약금액 < 0:
        lark.메시지보내기(토큰, chat_id, "⚠️ 매출 칸 형식(계약명·계약금액)을 못 찾았어요.")
        return True

    # 1) 기존 계약에 입금: 거래처+계약명으로 계약을 찾는다.
    #    (금액이 적은 '선금'도 잡아야 하므로 금액 일치를 필수로 두지 않는다 — 금액은 정렬 보조로만.)
    #    - 클라이언트를 슬래시로 명시했으면 → 그 거래처의 계약만 후보(흔한 단어 오매칭 방지).
    #    - 미명시면 → 계약명/거래처에 의미있는 토큰이 겹치는 계약만 후보(흔한 단어 제외).
    #    찾으면: 입금액 ≥ 계약금액 → 입금완료 / 입금액 < 계약금액 → 선수금(=선금, 미수금 남김).
    불용 = {"디자인", "제작", "인쇄", "작업", "월간", "정기", "및", "비", "외주"}
    토큰들 = [t for t in 힌트.split() if len(t) >= 2 and t not in 불용]
    클공백 = 클라이언트.replace(" ", "")
    후보 = []
    for 행 in 데이터[1:]:
        계약명 = str(행[i계약명]) if i계약명 < len(행) else ""
        클 = str(행[i클]) if 0 <= i클 < len(행) else ""
        계약금액 = _금액(행[i계약금액]) if i계약금액 < len(행) else 0
        기존입금 = _금액(행[i입금액]) if 0 <= i입금액 < len(행) else 0
        if not 계약명:
            continue
        텍스트 = 계약명 + " " + 클
        if 클라이언트:
            행클공백 = 클.replace(" ", "")
            if not (행클공백 and (클공백 in 행클공백 or 행클공백 in 클공백)):
                continue            # 거래처 명시했는데 안 맞으면 후보 아님
            점수 = 1 + sum(1 for t in 토큰들 if t in 텍스트)   # 거래처 일치 기본 + 계약명 토큰 가산
        else:
            점수 = sum(1 for t in 토큰들 if t in 텍스트)
            if 점수 == 0:
                continue            # 이름이 아예 안 겹치면 후보 아님
        후보.append((점수, 1 if 계약금액 == 입금액 else 0, 계약명, 계약금액, 기존입금))

    if 후보 and not 강제신규:
        # 금액 일치 우선, 그다음 이름 점수 높은 순으로 1건 선택
        후보.sort(key=lambda x: (x[1], x[0]), reverse=True)

        # 확신이 낮으면(공용단어 1개로 낚임, 또는 동점 후보 다수) 자동기록하지 않고 되묻는다.
        if _애매한가(후보, 클라이언트):
            이름들 = " · ".join(c[2] for c in 후보[:2])
            lark.메시지보내기(
                토큰, chat_id,
                "🤔 '%s' %s원 — 어느 계약인지 확실치 않아요.\n"
                "   비슷한 계약: %s\n"
                "   맞으면 '거래처 / 계약명 / 금액 입금'처럼 정확히,\n"
                "   시트에 없는 새 계약이면 '새 계약 %s %s 입금'으로 다시 보내주세요."
                % (계약명입력, format(입금액, ","), 이름들, 계약명입력, 입금액))
            return True

        _, _, 계약명c, 계약금액c, 기존입금c = 후보[0]
        누적 = 기존입금c + 입금액      # 분할입금 합계: 이번 받은 금액을 기존 입금액에 더한다
        if 누적 >= 계약금액c:
            상태, 미수금 = "입금완료", 0
        else:
            상태, 미수금 = "선수금", 계약금액c - 누적
        응답 = 시트.매칭수정(
            자금설정["endpoint"], 자금설정["key"], "매출",
            {"계약명": 계약명c, "계약금액": 계약금액c},
            {"입금일": 결과["날짜"], "입금액": 누적, "입금상태": 상태})
        if 응답.get("ok"):
            누적표시 = "" if 기존입금c == 0 else " (누적 %s원)" % format(누적, ",")
            if 상태 == "선수금":
                문구 = "✅ 선금 입금 — %s\n   이번 %s원 받음%s · 미수금 %s원 (계약 %s원) · %s" % (
                    계약명c, format(입금액, ","), 누적표시, format(미수금, ","),
                    format(계약금액c, ","), 결과["날짜"][5:])
            else:
                문구 = "✅ 매출 입금 — %s\n   이번 %s원 받음%s · 입금완료 · %s" % (
                    계약명c, format(입금액, ","), 누적표시, 결과["날짜"][5:])
            lark.메시지보내기(토큰, chat_id, 문구)
        else:
            lark.메시지보내기(토큰, chat_id, "⚠️ '%s' 입금 기록 중 문제: %s" % (
                계약명c, 응답.get("error", "알 수 없음")))
        return True

    # 2) 시트에서 계약을 못 찾음. '새 계약' 확인이 없으면 바로 추가하지 않고 되묻는다.
    if not 강제신규:
        lark.메시지보내기(
            토큰, chat_id,
            "🆕 '%s' %s원 — 시트에서 계약을 못 찾았어요.\n"
            "   새 계약이면 '새 계약 %s %s 입금'으로 다시 보내주시면 매출로 추가할게요.\n"
            "   (기존 계약 입금이면 정확한 계약명이나 '거래처 / 계약명'으로 보내주세요.)"
            % (계약명입력, format(입금액, ","), 계약명입력, 입금액))
        return True

    # 사용자가 '새 계약'으로 확인함 → 새 매출 줄 추가. 부가세 포함 총액에서 부가세 자동 분리.
    부가세 = 입금액 - round(입금액 / 1.1)
    공급가 = 입금액 - 부가세
    신규행 = []
    for h in 헤더:
        if h in ("계약일", "입금일"):
            신규행.append(결과["날짜"])
        elif h == "계약명":
            신규행.append(계약명입력)
        elif h == "클라이언트":
            신규행.append(클라이언트)
