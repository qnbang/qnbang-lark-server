# 계약서 방에 PDF/사진/docx를 올리면 → 다운로드 → 제미나이로 읽어 → 매출/정기매출 칸에 등록.
# 확인 답장은 무료 웹훅으로(봇 API 월 한도와 무관). 복합계약은 사람이 답장 보고 보정.
def 계약서메시지처리(토큰, 계약서설정, 자금설정, chat_id, message_id, file_key, 파일명, 종류):
    웹훅 = 계약서설정.get("webhook")

    def 답(t):
        if 웹훅:
            lark.웹훅보내기(웹훅, t)
        else:
            lark.메시지보내기(토큰, chat_id, t)   # 웹훅 없으면 봇으로(월 한도 걸리면 안 갈 수 있음)

    if not 자금설정:
        답("⚠️ 자금기록기 설정(config '자금')이 없어요.")
        return
    try:
        바이트 = lark.파일다운로드(토큰, message_id, file_key, 종류)
    except Exception as e:
        답("⚠️ 계약서 파일을 못 받았어요: %s" % e)
        return

    import os
    import tempfile
    ext = os.path.splitext(파일명)[1].lower() or (".jpg" if 종류 == "image" else ".pdf")
    with tempfile.NamedTemporaryFile(suffix=ext, delete=False) as tf:
        tf.write(바이트)
        경로 = tf.name
    try:
        r = 계약서AI해석.해석_파일(경로, 계약서설정.get("gemini") or {})
    finally:
        os.unlink(경로)
    if not r.get("ok"):
        답("🔎 계약서에서 정보를 못 뽑았어요: %s" % r.get("이유", ""))
        return

    금액 = r["금액"]
    부가세 = 금액 - round(금액 / 1.1)
    공급가 = 금액 - 부가세
    오늘 = datetime.now().strftime("%Y/%m/%d")
    계약일 = (r.get("계약일") or "").replace("-", "/") or 오늘

    if r["종류"] == "정기매출":
        헤더목록 = 시트.탭읽기(자금설정["endpoint"], 자금설정["key"], "정기매출")
        헤더 = 헤더목록[0] if 헤더목록 else [
            "항목", "클라이언트", "월금액", "부가세", "입금예정일", "시작월", "종료월", "활성", "비고"]
        값 = {"항목": r["계약명"], "클라이언트": r["거래처"], "월금액": 금액, "부가세": 부가세,
              "시작월": r.get("시작월") or "", "종료월": r.get("종료월") or "",
              "활성": "Y", "비고": r.get("비고") or "계약서 자동등록"}
        금액라벨 = "월금액"
        탭 = "정기매출"
    else:
        헤더목록 = 시트.탭읽기(자금설정["endpoint"], 자금설정["key"], "매출")
        헤더 = 헤더목록[0] if 헤더목록 else [
            "계약일", "계약명", "클라이언트", "계약금액", "부가세", "입금상태",
            "입금일", "입금예정일", "입금액", "순매출", "비고"]
        값 = {"계약일": 계약일, "계약명": r["계약명"], "클라이언트": r["거래처"],
              "계약금액": 금액, "부가세": 부가세, "입금상태": "입금대기", "순매출": 공급가,
              "비고": r.get("비고") or "계약서 자동등록"}
        금액라벨 = "계약금"
        탭 = "매출"

    행 = [값.get(h, "") for h in 헤더]
    응답 = 시트.행추가(자금설정["endpoint"], 자금설정["key"], 탭, 행, 헤더)
    if 응답.get("ok"):
        답("✅ 계약서 등록 — [%s]\n   거래처: %s\n   건명: %s\n   %s: %s원 (공급가 %s · 부가세 %s)\n   ※ 매출/정기 분류나 복합계약이면 알려주세요." % (
            r["종류"], r["거래처"], r["계약명"], 금액라벨,
            format(금액, ","), format(공급가, ","), format(부가세, ",")))
    else:
        답("⚠️ 시트 등록 중 문제: %s" % 응답.get("error", "알 수 없음"))


